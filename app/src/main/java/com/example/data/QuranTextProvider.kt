    fun getPage(pageNumber: Int): PageContent {
        val clampedPage = pageNumber.coerceIn(1, 604)
        val surah = QuranMetadata.getSurahForPage(clampedPage)
        val juz = ((clampedPage - 1) / 20 + 1).coerceIn(1, 30)

        val ayahs = samples[clampedPage] ?: generatePageVerses(clampedPage, surah)

        return PageContent(
            pageNumber = clampedPage,
            surah = surah,
            juzNumber = juz,
            ayahs = ayahs
        )
    }

